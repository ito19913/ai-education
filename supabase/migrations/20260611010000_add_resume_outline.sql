-- レジュメ構造化 R11-① (見出しの完全統一、2026-06-11 grill R11-1〜R11-8 確定)。
--
-- 冊 (resumes) に「アウトライン」を持たせる。アウトライン = 章 (Ⅰ レベル) の配列で、
-- 各章が配下ピース (note_entries.id) の表示順を持つ:
--   [{ "id": "sec-1", "title": "文型と文の要素", "entryIds": ["uuid", ...] }, ...]
--
--   - Ⅰ (ローマ数字) = 章 = このアウトラインの section。
--     1 (アラビア数字) = 概念 = 配下ピース (entryIds の順で採番)。
--     (1)・①②③ はピース本文内の記法 (R11-1)。番号は表示時レンダリングで
--     Ⅰ→1→(1)→①→・ に固定 (R11-3、データはレベルだけ持つ)。
--   - ピースの配置はこの JSONB が唯一の置き場 (note_entries に列を足さない)。
--     どの章にも居ないピースは通し文書の末尾「未整理」に出す。
--   - null = アウトライン未生成 (AI 下書きは子の操作で初めて作る、R11-2)。
-- ============================================================================

alter table public.resumes
  add column if not exists outline jsonb;

comment on column public.resumes.outline is
  'レジュメ冊のアウトライン (R11)。[{id, title, entryIds[]}] の配列。null = 未生成';
